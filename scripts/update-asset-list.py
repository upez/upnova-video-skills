#!/usr/bin/env python3
"""Rebuild skills/upnova-illustrations/assets.tsv and ASSETS.md after adding or removing assets.

Small files go in skills/upnova-illustrations/assets/<path> (installed with the skill),
big ones (videos, screenshots, source footage) in media/<path> (downloaded on demand).
Run from anywhere: python3 scripts/update-asset-list.py
"""
import glob, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ILL = os.path.join(ROOT, "skills/upnova-illustrations")

rows = []
for base, where in ((ILL, "skill"), (os.path.join(ROOT, "media"), "repo")):
    for sub in (("assets",) if where == "skill" else ("assets", "sources")):
        for dp, _, fs in os.walk(os.path.join(base, sub)):
            for f in fs:
                if f.startswith("."):
                    continue
                full = os.path.join(dp, f)
                rows.append((os.path.relpath(full, base), where, os.path.getsize(full)))
rows.sort()
with open(os.path.join(ILL, "assets.tsv"), "w") as fh:
    fh.write("# path\twhere (skill = installed with the skill, repo = media/ in upez/upnova-video-skills)\tbytes\n")
    for r in rows:
        fh.write("%s\t%s\t%d\n" % r)

uses = {}
for t in glob.glob(os.path.join(ROOT, "skills/*/templates/**/*.html"), recursive=True):
    s = open(t).read().replace("%20", " ")
    name = os.path.relpath(t, os.path.join(ROOT, "skills")).replace("/templates/", "/")[:-5]
    for p, _, _ in rows:
        if p in s or (p.startswith("assets/logos/logo-") and "assets/logos/logo-" in s):
            uses.setdefault(p, set()).add(name)


def size(b):
    return "%.1f MB" % (b / 1048576) if b >= 1048576 else "%d KB" % max(1, b // 1024)


groups = {}
for p, w, b in rows:
    parts = p.split("/")
    key = parts[1] if parts[0] == "assets" and len(parts) > 2 else ("sounds" if parts[0] == "assets" else parts[0])
    groups.setdefault(key, []).append((p, w, b))

out = ["# Assets", "",
       "Every file the templates use. Generated by `scripts/update-asset-list.py`; don't edit by hand.", "",
       "- **skill**: installed with the `upnova-illustrations` skill (`skills/upnova-illustrations/<path>`).",
       "- **repo**: kept in this repo's `media/<path>` and downloaded on demand.", "",
       "Get them into a project with `skills/upnova-illustrations/scripts/fetch-assets.sh <project> <template or path>`.", "",
       "Not shared, made per reel: `assets/presenter-cutout-<name>.webm` (the speaker cut out of that reel's own footage) and the reel's own footage.", ""]
for k in sorted(groups):
    out += ["## " + k, "", "| File | Where | Size | Used by |", "| --- | --- | --- | --- |"]
    for p, w, b in groups[k]:
        u = ", ".join(sorted(uses.get(p, []))) or ("source footage for recuts" if p.startswith("sources/") else "-")
        out.append("| `%s` | %s | %s | %s |" % (p, w, size(b), u))
    out.append("")
open(os.path.join(ROOT, "ASSETS.md"), "w").write("\n".join(out))
print("%d assets listed" % len(rows))
